-- H2 本地文件数据库初始化脚本。F1 在此基础上补充业务表。
CREATE TABLE IF NOT EXISTS t_evops_schema_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_evops_schema_version UNIQUE (version_no)
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('base-0', 'EVOPS 初始工作区');

-- ============================================================
-- F1 风电叶片巡检台账
-- 归属口径：风机服役窗口、叶片归属窗口统一为左闭右开 [起, 止)。
-- ============================================================

-- 风机档案：场址、机型、并网时间
CREATE TABLE IF NOT EXISTS t_turbine (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turbine_no VARCHAR(64) NOT NULL,
    site VARCHAR(128) NOT NULL,
    model VARCHAR(64) NOT NULL,
    grid_connected_at TIMESTAMP NOT NULL,
    decommissioned_at TIMESTAMP NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'IN_SERVICE',
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL,
    CONSTRAINT uk_turbine_no UNIQUE (turbine_no)
);

-- 叶片档案：序列号、方位、材料；installed_at/removed_at 构成归属窗口 [installed_at, removed_at)
CREATE TABLE IF NOT EXISTS t_blade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blade_no VARCHAR(64) NOT NULL,
    serial_no VARCHAR(64) NOT NULL,
    blade_position VARCHAR(8) NOT NULL,
    material VARCHAR(64) NOT NULL,
    turbine_id BIGINT NOT NULL,
    installed_at TIMESTAMP NOT NULL,
    removed_at TIMESTAMP NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'IN_SERVICE',
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL,
    CONSTRAINT uk_blade_no UNIQUE (blade_no),
    CONSTRAINT uk_blade_serial_no UNIQUE (serial_no)
);

-- 换件记录：保留旧件与新件的前后关系
CREATE TABLE IF NOT EXISTS t_blade_replacement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turbine_id BIGINT NOT NULL,
    blade_position VARCHAR(8) NOT NULL,
    old_blade_id BIGINT NOT NULL,
    new_blade_id BIGINT NOT NULL,
    replaced_at TIMESTAMP NOT NULL,
    reason VARCHAR(255) NULL,
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL
);

-- 巡检工单：关联无人机影像；状态 PENDING/INSPECTED/DEFECT_REGISTERED/REPAIRED/ACCEPTED/CLOSED
CREATE TABLE IF NOT EXISTS t_inspection_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no VARCHAR(64) NOT NULL,
    turbine_id BIGINT NOT NULL,
    blade_id BIGINT NULL,
    inspect_time TIMESTAMP NULL,
    drone_image_url VARCHAR(512) NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'PENDING',
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL,
    CONSTRAINT uk_inspection_order_no UNIQUE (order_no)
);

-- 缺陷登记：缺陷等级、维修结果、验收结论
CREATE TABLE IF NOT EXISTS t_defect (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    blade_id BIGINT NOT NULL,
    defect_level VARCHAR(16) NOT NULL,
    description VARCHAR(512) NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'OPEN',
    repair_result VARCHAR(512) NULL,
    repaired_at TIMESTAMP NULL,
    accepted_at TIMESTAMP NULL,
    accept_remark VARCHAR(255) NULL,
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('f1-1', 'F1 风电叶片巡检台账：风机/叶片/换件/巡检工单/缺陷');

-- ============================================================
-- F2 无人机叶片巡检航线
-- 航线按 风机+叶片方位+拍摄距离 配置；航线内容版本化，发布生效。
-- 发布前校验：临时禁飞区 / 风速条件 / 电量余量，冲突给出坐标和原因。
-- 新版本只作用于未起飞任务；历史影像继续引用原航线版本。
-- 临时改线走两级审批并留版本差异；审批只完成一半时停留待处理。
-- 航线规划与禁飞区的关键动作写入 t_audit_event，全程可追溯。
-- ============================================================

-- 巡检工单关联飞行任务与航线版本：历史影像始终引用拍摄时的原航线版本
ALTER TABLE t_inspection_order ADD COLUMN IF NOT EXISTS flight_task_id BIGINT NULL;
ALTER TABLE t_inspection_order ADD COLUMN IF NOT EXISTS route_version_id BIGINT NULL;

-- 航线：一条航线 = 风机 + 叶片方位 + 拍摄距离 的唯一组合
CREATE TABLE IF NOT EXISTS t_flight_route (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_no VARCHAR(64) NOT NULL,
    turbine_id BIGINT NOT NULL,
    blade_position VARCHAR(8) NOT NULL,
    shoot_distance_m DOUBLE NOT NULL,
    name VARCHAR(128) NULL,
    current_version_id BIGINT NULL,
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL,
    CONSTRAINT uk_flight_route_no UNIQUE (route_no),
    CONSTRAINT uk_flight_route_dim UNIQUE (turbine_id, blade_position, shoot_distance_m)
);

-- 航线版本：航点串、预计航程、电量与风速限值；状态 DRAFT/PUBLISHED/RETIRED
CREATE TABLE IF NOT EXISTS t_flight_route_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id BIGINT NOT NULL,
    version_no INT NOT NULL,
    waypoints_json VARCHAR(8192) NOT NULL,
    waypoint_count INT NOT NULL,
    estimated_distance_m DOUBLE NULL,
    required_battery_pct INT NULL,
    max_wind_speed DOUBLE NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    check_result_json VARCHAR(8192) NULL,
    published_at TIMESTAMP NULL,
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL,
    CONSTRAINT uk_route_version UNIQUE (route_id, version_no)
);

-- 禁飞区：临时/永久；多边形顶点 + 限飞高度 + 生效窗口；只取消不删除，保留追溯
CREATE TABLE IF NOT EXISTS t_no_fly_zone (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_no VARCHAR(64) NOT NULL,
    name VARCHAR(128) NOT NULL,
    zone_type VARCHAR(16) NOT NULL,
    polygon_json VARCHAR(8192) NOT NULL,
    vertex_count INT NOT NULL,
    max_altitude_m DOUBLE NULL,
    effective_from TIMESTAMP NOT NULL,
    effective_to TIMESTAMP NULL,
    reason VARCHAR(255) NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL,
    CONSTRAINT uk_no_fly_zone_no UNIQUE (zone_no)
);

-- 飞行任务：创建时绑定当前发布版本；未起飞任务随新版本改绑，已起飞任务保持原版本
CREATE TABLE IF NOT EXISTS t_flight_task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_no VARCHAR(64) NOT NULL,
    route_id BIGINT NOT NULL,
    route_version_id BIGINT NOT NULL,
    turbine_id BIGINT NOT NULL,
    blade_position VARCHAR(8) NOT NULL,
    planned_takeoff_at TIMESTAMP NULL,
    takeoff_at TIMESTAMP NULL,
    completed_at TIMESTAMP NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PLANNED',
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL,
    CONSTRAINT uk_flight_task_no UNIQUE (task_no)
);

-- 临时改线申请：基于某个版本提出新航点串，留版本差异；两级审批，终审通过才生成新版本
CREATE TABLE IF NOT EXISTS t_route_change_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    change_no VARCHAR(64) NOT NULL,
    route_id BIGINT NOT NULL,
    base_version_id BIGINT NOT NULL,
    reason VARCHAR(255) NOT NULL,
    proposed_waypoints_json VARCHAR(8192) NOT NULL,
    proposed_required_battery_pct INT NULL,
    proposed_max_wind_speed DOUBLE NULL,
    diff_json VARCHAR(8192) NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    current_step INT NOT NULL DEFAULT 1,
    resulting_version_id BIGINT NULL,
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL,
    CONSTRAINT uk_route_change_no UNIQUE (change_no)
);

-- 改线审批记录：每级一条；任一级驳回即结案
CREATE TABLE IF NOT EXISTS t_route_change_approval (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    change_id BIGINT NOT NULL,
    step_no INT NOT NULL,
    approver VARCHAR(64) NOT NULL,
    decision VARCHAR(16) NOT NULL,
    opinion VARCHAR(255) NULL,
    decided_at TIMESTAMP NOT NULL,
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL,
    CONSTRAINT uk_change_approval_step UNIQUE (change_id, step_no)
);

-- 审计事件：航线规划与禁飞区的关键动作留痕，支撑可追溯
CREATE TABLE IF NOT EXISTS t_audit_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type VARCHAR(32) NOT NULL,
    entity_id BIGINT NOT NULL,
    action VARCHAR(32) NOT NULL,
    detail VARCHAR(2048) NULL,
    operator VARCHAR(64) NULL,
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('f2-1', 'F2 无人机叶片巡检航线：航线/版本/禁飞区/飞行任务/改线两级审批/审计追溯');

-- ============================================================
-- F3 叶片缺陷管理
-- 缺陷分类（裂纹/雷击/结冰/涂层剥落）按等级配置处置时限；
-- 巡检员在影像上标注位置、尺寸与截图；
-- 专家复核可升级或降级，初判等级 initial_level 永不覆盖；
-- 等级变化重新生成维修建议、重算处置时限并记录责任人；
-- 已关闭（ACCEPTED）缺陷只读，仅允许追加说明；
-- 影像标注可反查缺陷分类、原单、处理人与异常原因。
-- ============================================================

-- 缺陷登记扩展：分类、初判等级、维修建议、责任人、处置截止时间
ALTER TABLE t_defect ADD COLUMN IF NOT EXISTS defect_type VARCHAR(24) NULL;
ALTER TABLE t_defect ADD COLUMN IF NOT EXISTS initial_level VARCHAR(16) NULL;
ALTER TABLE t_defect ADD COLUMN IF NOT EXISTS repair_advice VARCHAR(512) NULL;
ALTER TABLE t_defect ADD COLUMN IF NOT EXISTS responsible_person VARCHAR(64) NULL;
ALTER TABLE t_defect ADD COLUMN IF NOT EXISTS dispose_deadline TIMESTAMP NULL;

-- 处置时限配置：缺陷类型 + 等级 唯一；advice_template 为维修建议模板
CREATE TABLE IF NOT EXISTS t_defect_dispose_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    defect_type VARCHAR(24) NOT NULL,
    defect_level VARCHAR(16) NOT NULL,
    dispose_hours INT NOT NULL,
    advice_template VARCHAR(512) NOT NULL,
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL,
    CONSTRAINT uk_defect_dispose_rule UNIQUE (defect_type, defect_level)
);

-- 影像标注：巡检员在影像上标注位置、尺寸与截图；冗余 order_id 便于反查原单
CREATE TABLE IF NOT EXISTS t_defect_annotation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    defect_id BIGINT NOT NULL,
    order_id BIGINT NOT NULL,
    image_url VARCHAR(512) NULL,
    position_desc VARCHAR(255) NOT NULL,
    size_desc VARCHAR(128) NOT NULL,
    screenshot_url VARCHAR(512) NOT NULL,
    annotated_by VARCHAR(64) NOT NULL,
    annotated_at TIMESTAMP NOT NULL,
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL
);

-- 专家复核记录：每次复核一条；from_level -> to_level，初判等级不受影响
CREATE TABLE IF NOT EXISTS t_defect_review (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    defect_id BIGINT NOT NULL,
    reviewer VARCHAR(64) NOT NULL,
    from_level VARCHAR(16) NOT NULL,
    to_level VARCHAR(16) NOT NULL,
    opinion VARCHAR(512) NULL,
    responsible_person VARCHAR(64) NOT NULL,
    reviewed_at TIMESTAMP NOT NULL,
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL
);

-- 追加说明：已关闭缺陷唯一允许的写操作；只增不改
CREATE TABLE IF NOT EXISTS t_defect_note (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    defect_id BIGINT NOT NULL,
    note VARCHAR(512) NOT NULL,
    noted_by VARCHAR(64) NOT NULL,
    noted_at TIMESTAMP NOT NULL,
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL
);


-- ============================================================
-- F4 高空作业排班
-- 读取风速/降雨/雷电三类安全窗口，结合人员资质、装备可用性与维修时长生成候选班次；
-- 三类窗口与作业区间一律按左闭右开 [起, 止) 取交集，取 [max(from), min(to))；
-- 窗口收窄只预警不改期（不静默改期），作业开始前必须二次确认天气；
-- 延期保留原计划与通知回执；过期资质人员不得排入任务。
-- 数据可能补传/补录/重试：同一 (来源, 来源单据号, 类型) 与同一 (风机, 原计划开始)
-- 只落一条可用结果。
-- ============================================================

-- 气象安全窗口：风速/降雨/雷电三类；同一风机可有多个不同来源/批次窗口
CREATE TABLE IF NOT EXISTS t_weather_window (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site VARCHAR(128) NOT NULL,
    turbine_id BIGINT NULL,
    weather_type VARCHAR(16) NOT NULL,
    window_from TIMESTAMP NOT NULL,
    window_to TIMESTAMP NOT NULL,
    -- 风速类窗口的安全上限（m/s）；降雨/雷电窗口该值为空，表示区间内无降雨/无雷电
    safe_max_value DOUBLE NULL,
    forecast_value DOUBLE NULL,
    source_channel VARCHAR(32) NOT NULL,
    source_doc_no VARCHAR(64) NOT NULL,
    -- 修正/补录预报：本窗口替换同一来源下的旧单据窗口；被替换窗口保留留痕但不再参与排班
    replaces_source_doc_no VARCHAR(64) NULL,
    received_at TIMESTAMP NOT NULL,
    -- 仅作补充说明，不作为生效条件；生效一律以 [window_from, window_to) 为准
    remark VARCHAR(255) NULL,
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL,
    CONSTRAINT uk_weather_window_doc UNIQUE (source_channel, source_doc_no, weather_type)
);


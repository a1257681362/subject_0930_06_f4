-- 高空作业班次：排班结果（候选/已确认）。原计划开始/结束一经生成不可变，
-- 延期只写 t_postponement，不修改本表计划时间，杜绝静默改期。
CREATE TABLE IF NOT EXISTS t_work_shift (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_no VARCHAR(64) NOT NULL,
    site VARCHAR(128) NOT NULL,
    turbine_id BIGINT NOT NULL,
    -- 维修工作内容与计划维修时长（分钟），决定候选班次需要的窗口长度
    work_content VARCHAR(255) NOT NULL,
    required_qual_type VARCHAR(32) NOT NULL,
    required_qual_level VARCHAR(16) NOT NULL,
    crew_size INT NOT NULL,
    duration_minutes INT NOT NULL,
    equipment_id BIGINT NULL,
    worker_ids VARCHAR(255) NOT NULL,
    -- 候选班次落在三类气象窗口交集中的可行区间
    feasible_from TIMESTAMP NOT NULL,
    feasible_to TIMESTAMP NOT NULL,
    -- 原计划（候选生成时刻）的开始/结束，永不修改
    planned_from TIMESTAMP NOT NULL,
    planned_to TIMESTAMP NOT NULL,
    current_start_at TIMESTAMP NOT NULL,
    current_finish_at TIMESTAMP NOT NULL,
    -- CANDIDATE(候选) / CONFIRMED(二次确认通过) / STARTED / COMPLETED / CANCELLED
    status VARCHAR(16) NOT NULL DEFAULT 'CANDIDATE',
    confirm_status VARCHAR(16) NOT NULL DEFAULT 'NONE',
    weather_snapshot_json VARCHAR(4096) NULL,
    confirmed_at TIMESTAMP NULL,
    started_at TIMESTAMP NULL,
    completed_at TIMESTAMP NULL,
    -- 候选来源批次：同一风机+原计划开始只生成一条可用结果（补传/补录/重试幂等）
    result_key VARCHAR(128) NOT NULL,
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL,
    CONSTRAINT uk_work_shift_result_key UNIQUE (result_key),
    CONSTRAINT uk_work_shift_no UNIQUE (shift_no)
);

-- 班次气象预警：窗口收窄（交集变短/起点后移/不再覆盖原计划）触发；只预警不改期
CREATE TABLE IF NOT EXISTS t_shift_warning (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_id BIGINT NOT NULL,
    warning_type VARCHAR(24) NOT NULL,
    weather_type VARCHAR(16) NULL,
    message VARCHAR(512) NOT NULL,
    old_from TIMESTAMP NULL,
    old_to TIMESTAMP NULL,
    new_from TIMESTAMP NULL,
    new_to TIMESTAMP NULL,
    -- 每次“收窄事件”一条；扫描任务对同一收窄状态幂等（内容相同不重复告警）
    warning_key VARCHAR(128) NOT NULL,
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL,
    CONSTRAINT uk_shift_warning_key UNIQUE (warning_key)
);

-- 延期记录：原计划保留，新开始时间另存；不回写 t_work_shift 的原计划字段
CREATE TABLE IF NOT EXISTS t_postponement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_id BIGINT NOT NULL,
    seq INT NOT NULL,
    original_from TIMESTAMP NOT NULL,
    original_to TIMESTAMP NOT NULL,
    new_from TIMESTAMP NOT NULL,
    new_to TIMESTAMP NOT NULL,
    reason VARCHAR(512) NOT NULL,
    operator VARCHAR(64) NULL,
    postponed_at TIMESTAMP NOT NULL,
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL,
    CONSTRAINT uk_postponement_seq UNIQUE (shift_id, seq)
);

-- 通知回执：延期/预警通知的送达回执；按 (班次, 延期序号, 通道) 幂等
CREATE TABLE IF NOT EXISTS t_notification_receipt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_id BIGINT NOT NULL,
    postponement_id BIGINT NULL,
    channel VARCHAR(32) NOT NULL,
    recipient VARCHAR(128) NOT NULL,
    content VARCHAR(1024) NOT NULL,
    -- PENDING / SENT / DELIVERED / FAILED
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    sent_at TIMESTAMP NULL,
    delivered_at TIMESTAMP NULL,
    error_msg VARCHAR(255) NULL,
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL,
    CONSTRAINT uk_notification_dedup UNIQUE (shift_id, postponement_id, channel)
);

